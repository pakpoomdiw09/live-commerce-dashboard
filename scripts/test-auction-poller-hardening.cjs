const { test } = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')

test('auction poller pages past 100 comments, keeps a per-round high-water cursor, and never retargets', () => {
  const route = fs.readFileSync('app/api/live-cf/auction/poll-comments/route.ts', 'utf8')
  assert.match(route, /searchParams\.set\('limit', '100'\)/)
  assert.match(route, /auction_poll_cursors/)
  assert.match(route, /high_water_at/)
  assert.match(route, /continuation_url/)
  assert.match(route, /paging\?\.next/)
  assert.match(route, /cursor_id: cursorId/)
  assert.match(route, /onConflict: 'cursor_id'/)
  assert.match(route, /const pollId = String\(target\.live_post_id\)/)
  assert.doesNotMatch(route, /fetchPageLiveVideos|live_post_aliases:\s*aliases|retargeted round/)
})

test('comment diagnostics report author-field presence and skip reasons without raw payloads', () => {
  const poller = fs.readFileSync('app/api/live-cf/auction/poll-comments/route.ts', 'utf8')
  const ingress = fs.readFileSync('lib/integrations/facebook/webhook-http.ts', 'utf8')
  const handler = fs.readFileSync('lib/integrations/facebook/webhook-handler.ts', 'utf8')
  assert.match(poller, /has_from: hasFrom/)
  assert.match(poller, /has_from_id: hasFromId/)
  assert.match(poller, /reason = 'MISSING_FROM_ID'/)
  assert.match(ingress, /decision: 'awaiting_queue_insert'/)
  assert.match(ingress, /has_from_id:/)
  assert.match(handler, /decision: canRouteComment \? 'sent_to_comment_handler' : 'skipped'/)
  assert.match(handler, /reason: isCommentPayload \? commentSkipReason : 'NOT_NEW_COMMENT'/)
  assert.doesNotMatch(handler, /raw_value:/)
})
